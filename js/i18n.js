function idiomaInicial() {
  const pedido = new URLSearchParams(location.search).get("lang");
  if (pedido in IDIOMAS) return pedido;
  try {
    const guardado = localStorage.getItem("uptime.idioma");
    if (guardado in IDIOMAS) return guardado;
  } catch { /* sin almacenamiento */ }
  return (navigator.languages || [navigator.language || "es"]).some((l) => /^es\b/i.test(l)) ? "es" : "en";
}
